//! Model-bundle manager + per-user state trees (CONTRACTS §7 "Bundle
//! layout", §4, §6.3; CE mechanics from
//! `re/findings/10-classifier/bundle-formats.md` §2 and the tree shape from
//! `re/findings/02-artifacts/classifier-data.md`).
//!
//! Bundle layout at `--model` (§4 `/usr/share/lustless/models/`):
//!
//! ```text
//! manifest.json                     plaintext: roles, versions, sha256 per artifact
//! <sha256>-scorer.onnx              content-addressed ONNX model
//! <sha256>-labels.json              content-addressed label map
//! <sha256>-calibration.json         content-addressed threshold calibration
//! ```
//!
//! [`load`] validates **every** hash at startup and fails closed on any
//! missing or corrupt artifact; the caller exits non-zero (§7). The artifact
//! *id* logged at startup is CE's `<20 hex>-<role>` shape
//! (`bundle-formats.md` §2.1: CE used the first 80 bits of the file hash —
//! we use the first 80 bits of the sha256).
//!
//! Per-user trees (CE `classifier-data.md` "Per-SID directory layout",
//! `91-linux-mapping.md` §2 "Per-user state — Adapt"):
//! * `--data` — `<data>/pdl/<ISO-ts>` work batches: the §6.3 spool
//!   transactions the daemon writes and this process consumes,
//! * `--cache` — small control files in the CE `bmdat` namespace plus the
//!   `<pid>.log` fallback directory (`bmdat/nxu.dat`-style update-schedule
//!   marker has no LustLess counterpart: model bundles ship with packages,
//!   CONTRACTS §12 — our control file is `bmdat/last-result.json`, written
//!   after every consumed batch and read back at startup for support logs).

use std::collections::HashMap;
use std::fs::{self, File, OpenOptions};
use std::io::{self, Write};
use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt, PermissionsExt};
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

/// The bundle manifest file inside `--model`.
pub const MANIFEST_FILE: &str = "manifest.json";
/// Supported manifest `schemaVersion` major (our own format, v1).
const MANIFEST_SCHEMA_MAJOR: char = '1';
/// Length of the content id prefix in an artifact id (CE: 20 hex chars =
/// first 80 bits of the file hash, `bundle-formats.md` §2.1).
const ID_PREFIX_LEN: usize = 20;

/// Artifact roles required by §7.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    /// The ONNX scoring model.
    Scorer,
    /// The label map (`id2label`).
    Labels,
    /// Threshold calibration.
    Calibration,
}

impl Role {
    /// Every required role, in the canonical order used for ids/logs.
    pub const ALL: [Role; 3] = [Role::Scorer, Role::Labels, Role::Calibration];

    /// Lowercase role token (manifest + file names).
    pub fn as_str(self) -> &'static str {
        match self {
            Role::Scorer => "scorer",
            Role::Labels => "labels",
            Role::Calibration => "calibration",
        }
    }

    /// File extension of the role's artifact.
    pub fn ext(self) -> &'static str {
        match self {
            Role::Scorer => "onnx",
            Role::Labels | Role::Calibration => "json",
        }
    }
}

/// One `artifacts[]` entry of the manifest.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ArtifactEntry {
    /// Required role.
    pub role: Role,
    /// Artifact version (upstream model revision or our calibration version).
    pub version: String,
    /// Lowercase hex sha256 of the artifact file.
    pub sha256: String,
    /// File name inside `--model`: `<sha256>-<role>.<ext>`.
    pub file: String,
}

/// Provenance block of the manifest (surfaced in startup logs and the §5
/// diagnostics `versions.txt`, which embeds `manifest.json`).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ModelInfo {
    /// Upstream model id, e.g. `AdamCodd/vit-base-nsfw-detector`.
    pub name: String,
    /// Upstream revision the artifacts were fetched at.
    pub revision: String,
    /// Model license.
    pub license: String,
    /// Provenance URL.
    pub source: String,
}

/// The bundle manifest (`models/manifest.json`, generated by
/// `fetch-model.sh`).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BundleManifest {
    /// Manifest format version; must be `1.x`.
    #[serde(rename = "schemaVersion")]
    pub schema_version: String,
    /// Bundle version (cosmetic; logged at startup).
    #[serde(rename = "bundleVersion")]
    pub bundle_version: String,
    /// Upstream provenance.
    pub model: ModelInfo,
    /// Content-addressed artifacts, exactly one per [`Role::ALL`].
    pub artifacts: Vec<ArtifactEntry>,
}

/// A validated artifact ready for use.
#[derive(Debug, Clone, PartialEq)]
pub struct Artifact {
    /// Its role.
    pub role: Role,
    /// Version from the manifest.
    pub version: String,
    /// sha256 from the manifest (verified against the file bytes).
    pub sha256: String,
    /// Content id: `<sha256[..20]>-<role>` (CE `<id>-<role>` shape).
    pub id: String,
    /// Absolute (or model-dir-joined) path of the verified file.
    pub path: PathBuf,
}

/// A fully hash-validated bundle.
#[derive(Debug, Clone)]
pub struct LoadedBundle {
    /// Bundle version from the manifest.
    pub bundle_version: String,
    /// Upstream provenance.
    pub model: ModelInfo,
    /// Verified artifacts.
    pub scorer: Artifact,
    /// Verified labels artifact.
    pub labels: Artifact,
    /// Verified calibration artifact.
    pub calibration: Artifact,
}

impl LoadedBundle {
    /// The three artifacts in canonical role order.
    pub fn artifacts(&self) -> [&Artifact; 3] {
        [&self.scorer, &self.labels, &self.calibration]
    }

    /// Content-addressed artifact ids in canonical role order — the §7
    /// `hello {model_ids}` payload.
    pub fn ids(&self) -> Vec<String> {
        self.artifacts().iter().map(|artifact| artifact.id.clone()).collect()
    }
}

/// Bundle / state-tree failures. Every variant is fail-closed (§7).
#[derive(Debug, thiserror::Error)]
pub enum BundleError {
    #[error("model manifest missing: {0}")]
    ManifestMissing(PathBuf),
    #[error("model manifest unreadable at {path}: {source}")]
    ManifestIo {
        path: PathBuf,
        #[source]
        source: io::Error,
    },
    #[error("model manifest parse failed: {0}")]
    ManifestParse(#[from] serde_json::Error),
    #[error("model manifest schema {0} is not supported (want {MANIFEST_SCHEMA_MAJOR}.x)")]
    UnsupportedSchema(String),
    #[error("model manifest is missing the {0} role")]
    MissingRole(&'static str),
    #[error("model manifest lists the {0} role twice")]
    DuplicateRole(&'static str),
    #[error("artifact {0}: sha256 is not 64 lowercase hex characters")]
    InvalidSha256(&'static str),
    #[error("artifact {role}: file {found} is not the content-addressed name {expected}")]
    FilenameMismatch {
        role: &'static str,
        expected: String,
        found: String,
    },
    #[error("artifact {role} missing: {path}")]
    ArtifactMissing {
        role: &'static str,
        path: PathBuf,
    },
    #[error("artifact {role} hash mismatch: manifest {expected}, file {actual}")]
    HashMismatch {
        role: &'static str,
        expected: String,
        actual: String,
    },
    #[error("state tree {path}: {source}")]
    Tree {
        path: PathBuf,
        #[source]
        source: io::Error,
    },
    #[error("control file {path}: {source}")]
    Control {
        path: PathBuf,
        #[source]
        source: io::Error,
    },
    #[error("control file {path} is not valid JSON: {source}")]
    ControlParse {
        path: PathBuf,
        #[source]
        source: serde_json::Error,
    },
}

fn is_sha256_hex(value: &str) -> bool {
    value.len() == 64
        && value
            .bytes()
            .all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

/// Stream a file through SHA-256 (artifacts are up to hundreds of MB).
fn sha256_file(path: &Path) -> io::Result<String> {
    let mut file = File::open(path)?;
    let mut hasher = Sha256::new();
    io::copy(&mut file, &mut hasher)?;
    Ok(format!("{:x}", hasher.finalize()))
}

/// Load `model_dir/manifest.json` and verify every artifact (§7: validate
/// every hash at startup; missing/corrupt ⇒ `Err`, never a degraded mode).
pub fn load(model_dir: &Path) -> Result<LoadedBundle, BundleError> {
    let path = model_dir.join(MANIFEST_FILE);
    let text = match fs::read_to_string(&path) {
        Ok(text) => text,
        Err(source) if source.kind() == io::ErrorKind::NotFound => {
            return Err(BundleError::ManifestMissing(path));
        }
        Err(source) => return Err(BundleError::ManifestIo { path, source }),
    };
    let manifest: BundleManifest = serde_json::from_str(&text)?;
    if !manifest.schema_version.starts_with(MANIFEST_SCHEMA_MAJOR) {
        return Err(BundleError::UnsupportedSchema(manifest.schema_version));
    }

    // Exactly one entry per required role (unknown roles fail earlier, at
    // deserialization — `Role` is a closed enum; duplicates land here).
    let mut by_role: HashMap<Role, &ArtifactEntry> = HashMap::new();
    for entry in &manifest.artifacts {
        if by_role.insert(entry.role, entry).is_some() {
            return Err(BundleError::DuplicateRole(entry.role.as_str()));
        }
    }
    for role in Role::ALL {
        if !by_role.contains_key(&role) {
            return Err(BundleError::MissingRole(role.as_str()));
        }
    }

    let mut validated: HashMap<Role, Artifact> = HashMap::new();
    for role in Role::ALL {
        let entry = by_role[&role];
        validated.insert(role, validate_artifact(model_dir, entry)?);
    }

    Ok(LoadedBundle {
        bundle_version: manifest.bundle_version,
        model: manifest.model,
        scorer: validated.remove(&Role::Scorer).expect("checked above"),
        labels: validated.remove(&Role::Labels).expect("checked above"),
        calibration: validated
            .remove(&Role::Calibration)
            .expect("checked above"),
    })
}

/// Verify one artifact: sha256 shape, content-addressed file name, presence
/// and byte-exact hash.
fn validate_artifact(model_dir: &Path, entry: &ArtifactEntry) -> Result<Artifact, BundleError> {
    let role = entry.role.as_str();
    if !is_sha256_hex(&entry.sha256) {
        return Err(BundleError::InvalidSha256(role));
    }
    let expected = format!("{}-{role}.{}", entry.sha256, entry.role.ext());
    if entry.file != expected {
        return Err(BundleError::FilenameMismatch {
            role,
            expected,
            found: entry.file.clone(),
        });
    }
    let path = model_dir.join(&entry.file);
    if !path.is_file() {
        return Err(BundleError::ArtifactMissing { role, path });
    }
    let actual = sha256_file(&path).map_err(|source| BundleError::Control {
        path: path.clone(),
        source,
    })?;
    if actual != entry.sha256 {
        return Err(BundleError::HashMismatch {
            role,
            expected: entry.sha256.clone(),
            actual,
        });
    }
    Ok(Artifact {
        role: entry.role,
        version: entry.version.clone(),
        sha256: entry.sha256.clone(),
        id: format!("{}-{role}", &entry.sha256[..ID_PREFIX_LEN]),
        path,
    })
}

